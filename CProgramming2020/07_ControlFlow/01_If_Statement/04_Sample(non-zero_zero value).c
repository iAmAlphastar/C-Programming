//header file
#include<stdio.h>

//if is successful or it is true

//Entry point function
int main()
{

    //Representing non zero values.
    
    if(1)
    {
        printf("if statement evaluates when its is true i.e. if(1) or non zero\n");
    }

    
    if(0)
    {
        printf("if statement fails to evaluates when its is false i.e. if(0)\n");
    }
    
    
    if(-1)
    {
        printf("if statement evaluates when its is true i.e. if(-1) or any non zero value\n");
    }
    
    
    if(44)
    {
        printf("if statement evaluates when its is true i.e. if(44) or non zero value\n");
    }
    
    
    return(0);
}


