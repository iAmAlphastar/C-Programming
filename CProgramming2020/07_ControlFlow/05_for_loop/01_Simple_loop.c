//Program : simple use of for loop
// print numbers from 0 - 100


#include<stdio.h>


int main()
{

    int i;
    
    printf("The number are printed using for loop from 0 - 100\n");
    for(i = 0; i <= 100 ; i++)
    {
        printf("\t%d\n",i);
    }
    
    return(0);
}
