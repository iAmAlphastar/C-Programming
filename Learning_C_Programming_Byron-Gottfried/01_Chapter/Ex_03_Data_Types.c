/*Exercise 3 — Different Data Types*/

#include <stdio.h>

int main()
{
    char grade = 'A';
    int count = 10;
    float temperature = 25.5f;
    double voltage = 12.3456;
    
    printf("grade %c\n",grade);
    printf("count %d\n",count);
    printf("temperature %.2f\n",temperature);
    printf("voltage %lf\n", voltage);
    
    return(0);
}
